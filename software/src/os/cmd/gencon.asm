;
; Modifies:
;	Any
;
DEFPROC	genLocate
	mov	si,offset setPos
	jmp	short genArgs
ENDPROC	genLocate

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genScreen
;
; Generate code for "SCREEN [mode][,burst]"
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genScreen
	mov	si,offset setScreen
	jmp	short genArgs
ENDPROC	genScreen

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genWidth
;
; Generate code for "WIDTH columns"; "WIDTH device,width" (eg, WIDTH "COM1:",
; 255) is generated by genWidthDev.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genWidth
	mov	al,CLS_ANY
	call	peekNextToken
	jbe	gwd1
	cmp	ah,CLS_STR		; a device name (a string)?
	je	gwd0			; yes
	cmp	ah,CLS_VAR_STR
	jne	gwd1			; no
gwd0:	mov	dx,offset genWidthDev	; (see genfile.asm)
	jmp	genUpper
gwd1:	mov	si,offset setWidth	; fall into genArgs
ENDPROC	genWidth

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genArgs
;
; Generate code to push a series of numeric arguments (as longs), followed by
; the number of arguments, and then a call to the function in SI, which must
; begin by calling getArgs.  An omitted argument (eg, the 1st argument in
; "LOCATE ,5") is pushed as -1.
;
; Inputs:
;	SI = offset of function (in our CODE segment)
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genArgs
	push	si			; save the function
	sub	cx,cx			; CX = # args
ga1:	call	peekNextSymbol
	jbe	ga2			; not a symbol
	cmp	al,','			; omitted argument?
	jne	ga2			; no
	mov	si,ds:[PSP_HEAP]
	mov	bx,[si].TOKLET_NEXT	; consume the comma
	push	cx
	GENPUSH	-1,-1
	pop	cx
	inc	cx
	jmp	ga1
ga2:	call	genExpr
	jb	ga9
	je	ga8
	push	ax
	push	cx
	mov	al,VAR_LONG
	call	genCvtType		; arguments must be longs
	pop	cx
	pop	ax
	jc	ga9
	inc	cx
	cmp	al,','			; was the last symbol a comma?
	je	ga1			; yes, go back for more
ga8:	GENPUSH	cx
	pop	cx
	GENCALL	cx
	ret
ga9:	pop	si			; discard the function
	ret
ENDPROC	genArgs

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genEcho
;
; Process "ECHO".  If "ECHO ON" or "ECHO OFF", generate call to setFlags.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genEcho
	mov	al,CLS_KEYWORD
	call	getNextToken
	jb	gec9
	jnz	gec1
	GENCALL	printEcho
	ret
gec1:	cmp	al,TOK_ON
	jne	gec2
	mov	ah,NOT CMD_NOECHO
	jmp	short gec8
gec2:	cmp	al,TOK_OFF
	stc
	jne	gec9
	mov	ah,CMD_NOECHO
gec8:	mov	al,OP_MOV_AL
	stosw				; "MOV AL,xx" where XX is value in AH
	GENCALL	setFlags
gec9:	ret
ENDPROC	genEcho

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genPrint
;
; Generate code to "PRINT" a series of values.
;
; Inputs:
;	BX = offset of next TOKLET
;	ES:DI -> next unused location in code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genPrint
	call	peekNextSymbol
	jbe	genPrintArgs
	cmp	al,'#'			; PRINT #?
	jne	genPrintArgs		; no
	mov	dx,offset genPrintFile	; yes (see genfile.asm)
	jmp	genUpper
	DEFLBL	genPrintArgs,near
	mov	si,offset printArgs	; SI = runtime function
	DEFLBL	genPrintList,near
	push	si
	GENPUSHB VAR_NONE		; push end-of-args marker
gp1:	call	genExpr
	jnc	gp2
	test	dh,dh			; if there were no tokens
	stc				; then ignore the error
	jnz	gp9			; (PRINT without args is allowed)
gp2:	jz	gp8
	DEFLBL	genPrintVal,near	; (see genPrintf)
	push	ax
	mov	al,dl			; AL = VAR_LONG, VAR_STR, or VAR_DOUBLE
	GENPUSHB al
	pop	ax
	cmp	ah,CLS_KEYWORD		; did a keyword (eg, ELSE) end the
	je	gp8			; expression?
	cmp	ax,(CLS_SYM SHL 8) OR ':'; or a colon?
	je	gp8			; yes, so we're done
	mov	ah,VAR_COMMA		; comma (03h)
	cmp	al,','			; was the last symbol a comma?
	je	gp6			; yes
;
; Semi-colon is the other valid separator, but we no longer explicitly
; check for it, because historically PRINT presumes a semi-colon whenever
; a pair of values are separated only by whitespace (eg, if A = 2 and B = 3,
; "PRINT A B" behaves exactly like "PRINT A;B", displaying " 2  3").
;
; Unfortunately, in MSBASIC, that's only true for variables, not constants
; (eg, "PRINT 2 3" will print the number "23").  This is a parsing difference
; which we neither approve of nor emulate.
;
	mov	ah,VAR_SEMI		; presume semi-colon (02h) then
	test	al,al
	jz	gp8

gp6:	GENPUSHB ah			; "MOV AL,[VAR_SEMI or VAR_COMMA]"
	jmp	gp1			; continue processing arguments
gp8:	pop	cx
	GENCALL	cx			; all done
	ret
gp9:	pop	cx
	ret
ENDPROC	genPrint

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genRedir
;
; Check a line for ":>" (or ":>>"), which redirects the output of the entire
; line to a file (eg, PRINT "hello" :> TEST).  If found, the line's commands
; end before the ":>" (we trim both TOKLET_END and LINE_LEN, the latter for
; genDOS), and we generate a call to redirOut, along with a word in the code
; for redirOut to record the redirection; genRedirEnd ends it.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	If carry set, error (eg, no filename)
;	Otherwise, AX = 0 if no redirection; otherwise, AX = original LINE_LEN
;	(which the caller must restore), and DX:CX -> redirection word
;
; Modifies:
;	AX, CX, DX, SI, DI
;
DEFPROC	genRedir
	push	bx
	mov	si,ds:[PSP_HEAP]
	sub	bx,size TOKLET
	jmp	short gr1
gr0:	pop	bx			; no redirection (AX = 0, carry clear)
	ret
gr1:	add	bx,size TOKLET
	sub	ax,ax
	cmp	bx,[si].TOKLET_END	; any tokens left?
	jae	gr0			; no (and carry is clear)
	cmp	[bx].TOKLET_CLS,CLS_SYM
	jne	gr1
	mov	cx,[bx].TOKLET_OFF	; CX -> symbol in LINEBUF
	xchg	bx,cx
	cmp	word ptr [bx],'>:'	; ":>"?
	xchg	bx,cx
	jne	gr1
;
; The line's commands end at the ":>" (at CX).
;
	mov	[si].TOKLET_END,bx
	lea	bx,[si].LINEBUF		; BX -> LINEBUF
	sub	cx,bx			; CX = length of line before ":>"
	xchg	cx,[si].LINE_LEN	; CX = original length
	push	cx			; save it for the caller
	add	cx,bx			; CX -> end of line
	add	bx,[si].LINE_LEN	; BX -> ":>"
	lea	si,[bx+2]		; SI -> after ":>"
	mov	ax,1			; AX = 1 (create)
	cmp	byte ptr [si],'>'	; ":>>"?
	jne	gr2			; no
	inc	ax			; AX = 2 (append)
	inc	si
gr2:	cmp	si,cx			; skip leading whitespace
	jae	gr3
	cmp	byte ptr [si],' '
	ja	gr3
	inc	si
	jmp	gr2
gr3:	mov	bx,cx			; BX -> end of line
gr4:	cmp	bx,si			; trim trailing whitespace
	jbe	gr5
	cmp	byte ptr [bx-1],' '
	ja	gr5
	dec	bx
	jmp	gr4
gr5:	sub	bx,si			; BX = length of filename
	jz	gr8			; there's no filename
	push	ax			; save mode
	mov	ax,(2 SHL 8) OR OP_JMPS	; JMP over the redirection word
	stosw
	mov	cx,di			; CX = offset of redirection word
	sub	ax,ax
	stosw
	push	cx
	GENPUSH	es,cx			; push pointer to redirection word
	pop	cx
	pop	dx			; DX = mode
	push	cx
	GENPUSH	dx			; push mode
	GENPUSH	bx			; push length of filename
	mov	bx,ds:[PSP_HEAP]
	lea	cx,[bx].LINEBUF
	sub	si,cx			; SI = offset of filename in the line
	mov	cx,[bx].LINE_PTR.OFF
	add	cx,si
	mov	dx,[bx].LINE_PTR.SEG
	GENPUSH	dx,cx			; push pointer to filename
	GENCALL	redirOut
	pop	cx
	mov	dx,es			; DX:CX -> redirection word
	pop	ax			; AX = original length (carry clear)
	jmp	short gr9
gr8:	pop	ax			; discard original length
	stc
gr9:	pop	bx
	ret
ENDPROC	genRedir

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genRedirEnd
;
; Generate a call to redirEnd at the end of a line redirected by genRedir.
;
; Inputs:
;	DX:CX -> redirection word
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	AX, CX, DX, DI
;
DEFPROC	genRedirEnd
	mov	ax,16
	call	ensureRoom
	jc	gre9
	GENPUSH	dx,cx			; push pointer to redirection word
	GENCALL	redirEnd
gre9:	ret
ENDPROC	genRedirEnd

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genInput
;
; Generate code for "INPUT #n,var[,var]...", which reads the next item
; from the file into each variable (see fileItem), or "INPUT [prompt;|,]var
; [,var]...", which reads a line from the keyboard (see inputLine) and then
; takes each item from it the same way.  As in MSBASIC, a semicolon after the
; prompt (or no prompt) displays "? ", but a comma doesn't.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genInput
	sub	dx,dx			; DX = 0 (items)
gi0:	call	peekNextSymbol
	jbe	gi1
	cmp	al,'#'			; INPUT #?
	jne	gi1			; no
	mov	cx,dx			; CX = LINE INPUT flag
	mov	dx,offset genInputFile	; (see genfile.asm)
	jmp	genUpper
;
; INPUT from the keyboard, with an optional prompt.
;
gi1:	push	dx
	mov	al,CLS_STR
	call	peekNextToken		; is there a prompt?
	pop	dx
	jbe	gi3			; no
	push	dx
	call	genExpr			; push the prompt
	pop	dx
	jbe	gi8
	mov	cl,1			; CL = 1 to display "? "
	cmp	al,';'
	je	gi4
	mov	cl,0
	cmp	al,','
	je	gi4
	jmp	short gi8
gi3:	push	dx
	GENPUSH	0,0			; push an empty prompt
	pop	dx
	mov	cl,1
gi4:	test	dx,dx			; LINE INPUT?
	jz	gi5			; no
	mov	cl,2			; yes (and no "? ")
gi5:	mov	ch,0
	GENPUSH	cx			; push the flags
	GENCALL	inputLine
	mov	cx,offset fileItem
	jmp	genReadVars		; read the variables
gi8:	stc
	ret
ENDPROC	genInput

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genLineInput
;
; Generate code for "LINE INPUT #n,var$" or "LINE INPUT [prompt;]var$"
; (genLine calls us when LINE is followed by INPUT), which reads the next line
; from the file (or the keyboard) into var$.
;
; Inputs:
;	DS:BX -> TOKLETs (at INPUT)
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genLineInput
	call	skipToken		; consume INPUT
	mov	dx,1			; DX = 1 (lines)
	jmp	gi0
ENDPROC	genLineInput

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genLine
;
; LINE is both LINE INPUT (from the keyboard or a file) and a graphics
; statement, and since the graphics generators (see gengfx.asm) aren't part
; of COMMAND's core, LINE comes here, where we decide which kind of statement
; it is and then jump to genLineInput, or to the graphics generator via
; genUpper (see gencmd.asm), which reports "Not enough memory" if only the
; core was loaded.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genLine
	mov	al,CLS_KEYWORD
	call	peekNextToken		; LINE INPUT?
	jbe	gli1			; no
	cmp	al,TOK_INPUT
	jne	gli1			; no
	jmp	genLineInput		; yes
gli1:	mov	dx,offset genLineGfx
	jmp	genUpper
ENDPROC	genLine

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genWrite
;
; Generate code for "WRITE [#n,][expr[,expr]...]", which writes the values
; separated by commas, with strings in quotes (see writeValue).
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genWrite
	sub	cx,cx
	mov	dx,cx			; DX:CX = 0 (no file)
	call	peekNextSymbol
	jbe	gw1
	cmp	al,'#'			; WRITE #?
	jne	gw1			; no
	mov	dx,offset genWriteFile	; yes (see genfile.asm)
	jmp	genUpper
	DEFLBL	genWriteArgs,near	; (DX:CX -> redirection word)
gw1:	push	dx
	push	cx
	sub	cx,cx			; CX = # values
gw2:	push	cx
	call	genExpr			; push the next value
	pop	cx
	jnc	gw3
	test	dh,dh			; were there any tokens?
	stc
	jnz	gw7			; yes, so it's an error
gw3:	jz	gw6			; no value
	inc	cx
	push	cx
	push	ax
	mov	al,dl
	GENPUSHB al			; push its type
	pop	ax
	push	ax
	sub	al,','			; AL = 0 if a comma follows
	GENPUSHB al			; (ie, if it's not the last value)
	GENCALL	writeValue
	pop	ax
	pop	cx
	cmp	al,','			; another value?
	je	gw2			; yes
	jmp	short gw8
;
; If there are no values (or a comma ended the last one), end the line.
;
gw6:	GENPUSHB VAR_NONE
	GENCALL	printArgs
	clc
gw7:	jc	gw8a
;
; genPrintFile also ends here, with the redirection word on the stack.
;
	DEFLBL	genWriteEnd,near
gw8:	pop	cx
	pop	dx
	push	ax
	mov	ax,dx
	or	ax,cx			; was there a redirection word?
	pop	ax
	jz	gw9			; no
	jmp	genRedirEnd		; yes, so end the redirection
gw8a:	pop	cx
	pop	dx
gw9:	ret
ENDPROC	genWrite

CODE	ENDS

