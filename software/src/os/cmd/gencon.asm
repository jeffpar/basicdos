; Generates code for these console I/O statements:
;
;	CLS				(genCLS)
;	COLOR				(genColor)
;	ECHO				(genEcho)
;	LOCATE				(genLocate)
;	INPUT, LINE INPUT		(genInput, genLineInput, via genLine;
;					see genfile.asm for INPUT # and
;					LINE INPUT #)
;	PRINT				(genPrint; see genfile.asm for PRINT #)
;	WRITE				(genWrite; see genfile.asm for WRITE #)
;	SCREEN				(genScreen)
;	WIDTH				(genWidth)
;
; See gencmd.asm for an overview of all the gen*.asm files.  Like gencmd.asm,
; these functions are called while generating code, with DS:BX -> TOKLETs and
; ES:DI -> code block.
;
	include	cmd.inc
	include	gen.inc
	include	8086.inc

CODE    SEGMENT

	EXTNEAR	<genExpr,getNextToken,genCallCS,genPushImm,genPushImmByte>
	EXTNEAR	<genPushImmByteAL,genPushImmByteAH,genPushImmLong,genCvtType>
	EXTNEAR	<peekNextSymbol,peekNextToken,skipToken,genUpper,genReadVars>
	EXTNEAR	<genPrintFile,genWriteFile,genInputFile,genLineGfx,genWidthDev>
	EXTNEAR	<fileItem,inputLine,writeValue>
	EXTNEAR	<clearScreen,printArgs,printEcho,setColor,setFlags>
	EXTNEAR	<setPos,setScreen,setWidth,redirOut,redirEnd,ensureRoom>
	EXTABS	<TOK_OFF,TOK_ON,TOK_INPUT>

        ASSUME  CS:CODE, DS:DATA, ES:DATA, SS:DATA

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genCLS
;
; Generate code for "CLS"
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genCLS
	GENCALL	clearScreen
	ret
ENDPROC	genCLS

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genColor
;
; Generate code for "COLOR [fgnd][,[bgnd][,border]]"
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genColor
	mov	si,offset setColor
	jmp	short genArgs
ENDPROC	genColor

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
