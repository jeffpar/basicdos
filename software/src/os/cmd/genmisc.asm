; Generates code for DEF SEG, POKE, RANDOMIZE, SCREEN, SWAP, and WIDTH, whose
; runtime functions are in upmisc.asm.  This module is linked after CONST.OBJ,
; so it's outside COMMAND's core (see CMD.LRF): genCommands reports "Not enough
; memory" for these statements if only the core was loaded, and genDef checks
; DEF SEG with genUpper.
;
	DOSFUNC equ 1
	include	cmd.inc
	include	gen.inc
	include	arr.inc
	include	8086.inc

CODE	SEGMENT

	EXTNEAR	<genExpr,getNextToken,peekNextSymbol,peekNextToken>
	EXTNEAR	<getNextSymbol,genCallCS,genCvtType,genPushImm,genPushImmLong>
	EXTNEAR	<genPushImmByte,genPushImmByteAL,genPushImmByteAH>
	EXTNEAR	<genLongs,genArgs,genUpper,genWidthDev,genArrayRef,addVar>
	EXTNEAR	<genPushVarPtr>
	EXTNEAR	<defSeg,defSegBasic,pokeByte,randomize,setScreen,setWidth>
	EXTNEAR	<swapVars>

	ASSUME	CS:CODE, DS:DATA, ES:DATA, SS:DATA

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genDefSeg
;
; Generate code for "DEF SEG[=segment]" (after genDef has consumed DEF SEG).
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genDefSeg
	call	peekNextSymbol
	jbe	gds8			; no segment
	cmp	al,'='
	jne	gds8			; no segment
	mov	si,ds:[PSP_HEAP]
	mov	bx,[si].TOKLET_NEXT	; consume the '='
	mov	si,offset defSeg
	mov	cl,1
	jmp	genLongs
gds8:	GENCALL	defSegBasic
	clc
	ret
ENDPROC	genDefSeg

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genPoke
;
; Generate code for "POKE offset,value"
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genPoke
	mov	si,offset pokeByte
	mov	cl,2
	jmp	genLongs
ENDPROC	genPoke

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genRandomize
;
; Generate code for "RANDOMIZE [seed]" (see randomize).
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genRandomize
	call	genExpr			; push the seed, if any
	jnc	grz1
	test	dh,dh			; were there any tokens?
	stc
	jnz	grz9			; yes, so it's an error
grz1:	jz	grz2			; no seed
	mov	al,VAR_LONG
	call	genCvtType		; the seed must be a long
	jc	grz9
	sub	dx,dx			; DX = 0 (seed)
	jmp	short grz3
grz2:	GENPUSH	0,0			; push 0
	mov	dx,1			; DX = 1 (use the BIOS tick count)
grz3:	GENPUSH	dx			; push the flag
	GENCALL	randomize
	clc
grz9:	ret
ENDPROC	genRandomize

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genScreen
;
; Generate code for "SCREEN [mode][,burst]"
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genScreen
	mov	si,offset setScreen
	jmp	genArgs
ENDPROC	genScreen

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genWidth
;
; Generate code for "WIDTH columns"; "WIDTH device,width" (eg, WIDTH "COM1:",
; 255) is generated by genWidthDev.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genWidth
	mov	al,CLS_ANY
	call	peekNextToken
	jbe	gwd1
	cmp	ah,CLS_STR		; a device name (a string)?
	je	gwd0			; yes
	cmp	ah,CLS_VAR_STR
	jne	gwd1			; no
gwd0:	mov	dx,offset genWidthDev	; (see genfile.asm)
	jmp	genUpper
gwd1:	mov	si,offset setWidth
	jmp	genArgs
ENDPROC	genWidth

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genSwap
;
; Generate code for "SWAP var1,var2", which exchanges the values of two
; variables (or array elements) of the same type (see swapVars).
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	Carry clear if successful, set if error
;
; Modifies:
;	Any
;
DEFPROC	genSwap
	call	genVarRef		; push pointer to the 1st variable
	jc	gsw9
	push	ax			; AH = its type
	call	getNextSymbol
	jbe	gsw8
	cmp	al,','
	jne	gsw8
	call	genVarRef		; push pointer to the 2nd variable
	pop	dx			; DH = type of the 1st
	jc	gsw9
	cmp	ah,dh			; are the types the same?
	jne	gsw7			; no
	GENPUSHB ah			; push the type
	GENCALL	swapVars
	clc
	ret
gsw8:	pop	ax
gsw7:	stc
gsw9:	ret
ENDPROC	genSwap

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; genVarRef
;
; Generate code to push a pointer to a variable (or array element), for
; FIELD, LSET, RSET, and SWAP.
;
; Inputs:
;	DS:BX -> TOKLETs
;	ES:DI -> code block
;
; Outputs:
;	If carry clear, AH = type of the variable (VAR_LONG, VAR_STR, etc)
;
; Modifies:
;	Any
;
DEFPROC	genVarRef
	mov	al,CLS_VAR
	call	getNextToken
	jbe	gvr8
	and	ah,VAR_TYPE		; convert CLS_VAR_* to VAR_*
	mov	al,ARRAY_PTR
	call	genArrayRef		; array element?
	jc	gvr9			; error
	jnz	gvr7			; yes (AH = element type)
	call	addVar			; DX:SI -> var data
	jc	gvr9
	mov	cx,cs
	cmp	dx,cx			; constants (in CS) can't be set
	je	gvr8
	push	ax
	call	genPushVarPtr
	pop	ax
gvr7:	clc
	ret
gvr8:	stc
gvr9:	ret
ENDPROC	genVarRef

CODE	ENDS

	end
