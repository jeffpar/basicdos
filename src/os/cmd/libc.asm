;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; setColor
;
; Used by "COLOR [fgnd][,[bgnd][,border]]"
;
; As in MSBASIC, a foreground of 16-31 is a blinking foreground of 0-15,
; and in text modes, a background of 8-15 is the same as 0-7 (it never makes
; the foreground blink).  In graphics modes, the CON driver treats fgnd as
; the background color and bgnd as the palette.
;
; Inputs:
;	N numeric expressions pushed on stack (only 1st 3 are processed)
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX, SI, DI
;
DEFPROC	setColor,FAR
	call	getArgs			; AX = fgnd, DX = bgnd, CX = border
;
; IOCTL_SETCOLOR sets only the bits we ask it to (BL = fill bits, BH = border
; bits), so the colors that were omitted keep their current values.
;
	sub	bx,bx
	test	cx,cx			; border omitted?
	js	sc1			; yes
	dec	bh			; no, so set all its bits
sc1:	mov	ch,cl			; CH = border
	mov	cl,4
	test	dx,dx			; bgnd omitted?
	js	sc2			; yes
	and	dl,07h			; as in MSBASIC, a bgnd of 8-15 is 0-7
	shl	dl,cl			; (only fgnd can set the blink bit)
	mov	bl,70h
sc2:	and	dl,70h
	mov	cl,dl			; CL = bgnd (if any)
	test	ax,ax			; fgnd omitted?
	js	sc5			; yes
	or	bl,8Fh			; no, so set the fgnd and blink bits
	test	al,10h			; blinking foreground?
	jz	sc4			; no
	or	cl,80h			; yes
sc4:	and	al,0Fh
	or	cl,al
sc5:	mov	dx,bx			; CX = new colors, DX = bits to set
	mov	al,IOCTL_SETCOLOR
	call	ioctlCon
	ret
ENDPROC	setColor

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; setPos
;
; Used by "LOCATE [row][,[col][,cursor]]" (as with COLOR, any additional
; arguments, such as the cursor's scan lines, are ignored).  Row and col are
; 1-based, and cursor is 0 to hide the cursor or 1 to show it, until the next
; input (or, in a BAS program, see markCursor).  Nothing happens if STDOUT
; doesn't support cursor positioning.
;
; Inputs:
;	N numeric expressions pushed on stack (only 1st 3 are processed)
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX, SI, DI
;
DEFPROC	setPos,FAR
	call	getArgs			; AX = row, DX = col, CX = cursor
;
; IOCTL_SETPOS keeps the current row or col if we pass -1 for it, which is
; what an omitted argument already is.
;
	test	ax,ax			; row omitted?
	js	sp1			; yes
	dec	ax			; make it zero-based
	js	sp8			; row 0 is illegal
sp1:	test	dx,dx			; col omitted?
	js	sp2			; yes
	dec	dx
	js	sp8			; col 0 is illegal
sp2:	mov	dh,al			; DL = col, DH = row
	xchg	cx,dx			; CX = new position, DL = cursor
;
; Positioning or hiding the cursor means the program uses the screen.
;
	cmp	cx,-1			; row or col specified?
	jne	sp3			; yes
	test	dl,dl			; hide the cursor?
	jnz	sp4			; no
sp3:	call	markCursor
sp4:	mov	al,IOCTL_SETPOS
	call	ioctlCon
	jnc	sp9
	cmp	al,ERR_SEEK		; (outside the console)
	je	sp8			; anything else means unsupported
sp9:	ret
sp8:	jmp	strIllegal
ENDPROC	setPos

