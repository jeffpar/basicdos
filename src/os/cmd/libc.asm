;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; callDOS
;
; Process DOS command generated by genDOS (or built by showUsage).
;
; Inputs:
;	[pHandler] -> handler offset
;	[idKeyword] -> keyword ID
;	[cbCmdLine] == length of command line
;	[pCmdLine] -> seg:off of command line
;
; Outputs:
;	None; like PC DOS, the program continues whether or not the command
;	fails (after any error is reported), but ERRORLEVEL is set to 1 if
;	the command failed, or 0 if it succeeded (see parseDOS)
;
; Modifies:
;	AX, BX, CX, DX, SI, DI, ES
;
DEFPROC	callDOS,FAR
	ARGVAR	pHandler,word
	ARGVAR	idKeyword,word
	ARGVAR	cbCmdLine,word
	ARGVAR	pCmdLine,dword
	ENTER
	push	ds
	push	[idKeyword]
	mov	dx,[pHandler]
	mov	cx,[cbCmdLine]		; CX = length
	lds	si,[pCmdLine]		; DS:SI -> command
;
; The line at DS:SI may be sitting in LINEBUF, which is large enough to
; accommodate lines up to 255 characters.  However, DOS commands (at least
; external commands) are more constrained; for example, command tails
; are limited to 127 characters (see PSP_CMDTAIL).
;
; Since cmdFile (the function that processes external commands) also wants
; to use LINEBUF, we're going to copy as much as we can to space available
; in the PSP; but instead of starting at PSP_CMDTAIL, we'll start at PSP_FCB2,
; which provides enough room for a filename plus a command tail.
;
	push	ss
	pop	es
	mov	di,PSP_FCB2		; ES:DI -> PSP_FCB2
	cmp	cx,size PSP - PSP_FCB2 - 1
	jbe	cd1
	mov	cx,size PSP - PSP_FCB2 - 1
cd1:	push	cx
	push	es
	push	di
	rep	movsb
	mov	al,0			; null-terminate for good measure
	stosb
	pop	si
	pop	ds			; DS:SI -> PSP_FCB2
	pop	cx
	mov	bx,es:[PSP_HEAP]
	lea	di,[bx].TOKENBUF	; ES:DI -> TOKENBUF
	mov	[di].TOK_MAX,(size TOK_DATA) / (size TOKLET)
	DOSUTIL	TOKEN1
	ASSERT	NC
	call	splitCmd		; split "CD\" into "CD" and "\" (etc)
	pop	ax			; AX = keyword ID, if any
	mov	cl,[di].TOK_DATA[0].TOKLET_LEN
	call	parseDOS		; CX = length of first token only
	pop	ds
	LEAVE
	RETURN
ENDPROC	callDOS

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; redirOut
;
; Redirect STDOUT to a file for the rest of a line (see genRedir).
;
; Inputs:
;	[pRedir] -> redirection word (in the code block)
;	[idMode] = 1 to create (or truncate) the file, or 2 to append to it
;	[cbName] = length of filename
;	[pName] -> filename
;
; Outputs:
;	The redirection word records the previous STDOUT SFH (low byte) and
;	the file's handle (high byte); if the file can't be opened, the error
;	is reported and the program ends
;
; Modifies:
;	AX, BX, CX, DX, SI, DI, ES
;
DEFPROC	redirOut,FAR
	ARGVAR	pRedir,dword
	ARGVAR	idMode,word
	ARGVAR	cbName,word
	ARGVAR	pName,dword
	ENTER
	push	ds
	push	ss
	pop	es
	mov	bx,es:[PSP_HEAP]
	lea	di,[bx].LINEBUF		; ES:DI -> LINEBUF
	mov	dx,di
	mov	cx,[cbName]
	lds	si,[pName]		; DS:SI -> filename
	rep	movsb
;
; As with any other filename, the filename can be a string variable (eg,
; "PRINT X :> F$") or quoted (see openVar).
;
	push	ss
	pop	ds
	mov	si,dx			; DS:SI -> filename in LINEBUF
	mov	cx,[cbName]
	mov	ax,[idMode]
	call	openVar			; AX = handle
	jnc	ro1
	jmp	ctrlc			; an error ends the program
ro1:	xchg	bx,ax			; BX = handle
	mov	al,ds:[PSP_PFT][bx]	; AL = SFH of the file
	xchg	al,ds:[PSP_PFT][STDOUT]	; AL = previous STDOUT SFH
	mov	ah,bl			; AH = handle
	les	di,[pRedir]
	stosw				; record the redirection
	pop	ds
	LEAVE
	RETURN
ENDPROC	redirOut

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; redirEnd
;
; End a redirection started by redirOut (at the end of the line), restoring
; STDOUT and closing the file.  If control left the line some other way (eg,
; GOTO), cleanUp eventually restores STDOUT and closes the file instead.
; PRINT #, WRITE #, and LPRINT use this, too (see fileOut and prnOut), but
; their handle has bit 7 set, so the file stays open, and instead, we report
; any printer error (see chkOut), since writes to STDOUT ignore errors.
;
; Inputs:
;	[pRedirW] -> redirection word (in the code block)
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, SI
;
DEFPROC	redirEnd,FAR
	ARGVAR	pRedirW,dword
	ENTER
	push	ds
	lds	si,[pRedirW]
	sub	ax,ax
	xchg	ax,[si]			; AX = redirection word (and zero it)
	test	ax,ax			; is the redirection active?
	jz	re9			; no
	push	ss
	pop	ds
	mov	ds:[PSP_PFT][STDOUT],al	; restore STDOUT
	mov	bl,ah
	mov	bh,0			; BX = handle
	test	bl,bl			; is the file staying open?
	js	re8			; yes
	mov	ah,DOS_HDL_CLOSE
	int	21h
	jmp	short re9
re8:	and	bl,7Fh
	call	chkOut
re9:	pop	ds
	LEAVE
	RETURN
ENDPROC	redirEnd

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; chkOut
;
; Reports the last error that a printer (eg, PRN) had writing, if any: only
; printer drivers (see lptdev.asm) report errors for IOCTL_OUTSTATUS, while
; other devices (and files) report "unknown command" (22) or nothing.  The
; handle itself is invalid only if it's PRN and there's no PRN device (eg, no
; LPT1), so that's "Device unavailable".
;
; Inputs:
;	BX = handle
;
; Outputs:
;	None (an error occurs instead, if there was one)
;
; Modifies:
;	AX, DX
;
DEFPROC	chkOut
	mov	ax,(DOS_HDL_IOCTL SHL 8) OR IOCTL_OUTSTATUS
	int	21h			; did a printer report an error?
	jnc	co9			; no
	mov	dl,BERR_TIMEOUT		; "Device timeout"
	cmp	al,ERR_NOTREADY		; (from a time-out)
	je	co8
	mov	dl,BERR_NOPAPER		; "Out of paper"
	cmp	al,ERR_NOPAPER
	je	co8
	mov	dl,BERR_DEVFAULT	; "Device fault"
	cmp	al,ERR_WRFAULT
	je	co8
	mov	dl,BERR_NODEVICE	; "Device unavailable"
	cmp	al,ERR_BADHANDLE	; (no PRN device)
	jne	co9			; anything else isn't a printer error
co8:	xchg	ax,dx
	jmp	rtError
co9:	ret
ENDPROC	chkOut

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; clearScreen
;
; Used by "CLS".
;
; A program that asks for a console's own width (eg, WIDTH 40 in a 40-column
; console) gets the console without its border (the VKD$ driver's "virtual
; mode"), until it asks for the original width again.  If it never does (eg,
; it was aborted), a CLS outside a BAS program restores the console as well,
; with a mode of -1, which clears the console itself (and fails if there's
; nothing to restore).
;
; Inputs:
;	None
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX
;
DEFPROC	clearScreen,FAR
	mov	bx,ss:[PSP_HEAP]
	cmp	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,0
	jne	cs1			; a BAS program is running
	mov	cx,00FFh		; CL = -1 (and CH = 0: no rows)
	mov	al,IOCTL_SETMODE
	call	ioctlCon
	jnc	cs9			; restored (and cleared)
cs1:	call	markCursor		; (the program uses the screen)
	sub	cx,cx
	mov	dx,cx			; (DX is non-zero only to set rows)
	mov	al,IOCTL_SCROLL
	call	ioctlCon
cs9:	ret
ENDPROC	clearScreen

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; getArgs
;
; Removes the numeric arguments that genArgs pushed for a runtime function
; (ie, N arguments followed by N), and returns the first three in registers.
; Every argument must be 0-255, or -1 if it was omitted (which is also the
; value of any argument beyond N); otherwise, an "Illegal function call"
; error occurs.
;
; Call this first thing in the runtime function, so that the stack contains
; only our return address, the function's (far) return address, and the
; arguments.
;
; Inputs:
;	N arguments and N pushed on stack (see genArgs)
;
; Outputs:
;	AX = 1st argument, DX = 2nd argument, CX = 3rd argument
;	Stack cleaned (only the function's return address remains)
;
; Modifies:
;	AX, CX, DX, SI, DI
;
DEFPROC	getArgs
	push	bp
	mov	bp,sp
	mov	si,[bp+8]		; SI = N
	mov	ax,-1
	cwd
	mov	cx,ax
;
; Arguments are on the stack in reverse order, so as we load each one, we
; shift the previous ones down, ending with the 1st argument in AX.
;
ga1:	dec	si
	jl	ga8
	mov	cx,dx
	mov	dx,ax
	add	bp,4
	mov	ax,[bp+6]
	mov	di,[bp+8]		; DI:AX = next argument
	add	ax,1
	adc	di,0			; DI:AX = argument + 1
	jnz	ga9			; argument must be -1 to 255
	cmp	ax,256
	ja	ga9
	dec	ax
	jmp	ga1
;
; Move both return addresses above the arguments (whose last word is now at
; BP+8), restore BP, and point SP at the return addresses.  Every move is to
; a higher address, so no source is overwritten before it's read, and SP is
; updated last, since anything below SP can be overwritten by interrupts.
;
ga8:	mov	si,sp			; SS:SI -> saved BP
	mov	di,ss:[si+6]
	mov	[bp+8],di
	mov	di,ss:[si+4]
	mov	[bp+6],di		; the function's return address
	mov	di,ss:[si+2]
	mov	[bp+4],di		; our return address
	mov	si,ss:[si]
	lea	sp,[bp+4]
	mov	bp,si			; restore BP
	ret
ga9:	jmp	strIllegal
ENDPROC	getArgs

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; saveMode
;
; Called before a BAS program runs, to save the video mode (and the colors),
; so that they can be restored when the program ends (see restoreMode).  Only the outermost BAS
; program saves the mode (a BAS program run by another BAS program does not).
;
; The mode is saved in GFX_SAVED (as mode + 1, or 0 if none is saved), and
; setScreen sets bit 7 if the program then selects a graphics mode.
;
; Inputs:
;	None
;
; Outputs:
;	AX = 1 if the mode was saved, 0 if not
;
; Modifies:
;	AX
;
DEFPROC	saveMode
	push	bx
	push	cx
	push	dx
	mov	bx,ss:[PSP_HEAP]
	sub	ax,ax
	cmp	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,al	; already saved?
	jne	svm9			; yes
	mov	al,IOCTL_GETMODE
	mov	cl,0			; CL = 0 for the video mode
	call	ioctlCon		; DL = video mode
	mov	ax,0
	jc	svm9			; STDOUT doesn't support video modes
	inc	dx
	mov	bx,ss:[PSP_HEAP]
	mov	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,dl
	mov	al,IOCTL_GETCOLOR
	call	ioctlCon		; DL = fill, DH = border attributes
	mov	bx,ss:[PSP_HEAP]
	mov	ss:[bx].GFX_DATA.GFX_COLORS,dx
	mov	ax,1
svm9:	pop	dx
	pop	cx
	pop	bx
	ret
ENDPROC	saveMode

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; restoreMode
;
; Called when a BAS program ends (normally, or when it's aborted; see ctrlc),
; to restore the video mode saved by saveMode, if the program used a graphics
; mode (eg, with SCREEN 1; see setScreen), even if it then returned to a text
; mode (as DONKEY.BAS does, with SCREEN 0 leaving 40 columns), along with the
; colors the session had then (so that, for example, a program's COLOR 7,0,0
; doesn't leave the session's border black).  Otherwise, text-mode changes
; (eg, WIDTH 40 or SCREEN 0,0) persist, as in MSBASIC, which is what MODE.BAS
; relies on.  If the mouse was turned on (see mouseOn), it's turned off first.
;
; Inputs:
;	None
;
; Outputs:
;	None
;
; Modifies:
;	None
;
DEFPROC	restoreMode
	push	ax
	push	bx
	push	cx
	push	dx
	mov	bx,ss:[PSP_HEAP]
	cmp	byte ptr ss:[bx].GFX_DATA.MOUSE_STATE,0
	je	rsm1
	call	mouseReset
rsm1:	call	showCursor		; (hidden while the program ran)
	mov	cl,0
	xchg	cl,byte ptr ss:[bx].GFX_DATA.GFX_SAVED
	mov	ch,cl			; CH bit 7 set if graphics were used
	and	cl,3Fh			; (bit 6 if the screen was used)
	dec	cl			; CL = saved mode
	js	rsm9			; there isn't one
	push	cx
	mov	al,IOCTL_GETMODE
	mov	cl,0			; CL = 0 for the video mode
	call	ioctlCon		; DL = video mode
	pop	cx
	jc	rsm9
	cmp	dl,cl			; did the mode change?
	je	rsm9			; no
	test	ch,ch			; did the program use a graphics mode?
	js	rsm2			; yes, so restore the saved mode
	mov	al,dl
	sub	al,4
	cmp	al,3			; is it a graphics mode (4-6)?
	jae	rsm9			; no, so leave it (like MSBASIC)
rsm2:	mov	ch,0			; (no rows requested)
	mov	al,IOCTL_SETMODE
	call	ioctlCon		; yes, so restore it
	mov	bx,ss:[PSP_HEAP]
	mov	word ptr ss:[bx].GFX_DATA.GFX_FLAGS,0	; (and GFX_MODE)
	mov	cx,ss:[bx].GFX_DATA.GFX_COLORS
	mov	dx,-1			; (set every bit)
	mov	al,IOCTL_SETCOLOR
	call	ioctlCon		; and the colors, too
rsm9:	pop	dx
	pop	cx
	pop	bx
	pop	ax
	ret
ENDPROC	restoreMode

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; showCursor, hideCursor, markCursor, screenCursor
;
; As in MSBASIC, the cursor is hidden while a BAS program runs, except during
; keyboard input (see inputLine) and while an external program that it starts
; is running (see cmdFile), but only once the program uses the screen: once
; it sets a mode (see screenCursor), or clears the screen or positions or
; hides the cursor (see markCursor), which sets GFX_SAVED bit 6.  Until then,
; it leaves the cursor alone, like any other program (eg, the BAS utilities).
; A BAS program is running if saveMode saved its video mode, so nothing
; happens otherwise (or on a console that has no video modes, such as a
; terminal).
;
; markCursor hides the cursor only when it sets bit 6, so that a cursor shown
; with LOCATE ,,1 stays until the next input; screenCursor always hides it,
; since a mode change shows it again.
;
; Inputs:
;	None
;
; Outputs:
;	None
;
; Modifies:
;	None (other than flags)
;
DEFPROC	showCursor
	push	dx
	mov	dl,1			; DL = 1 to show the cursor
	jmp	short hcu1
	DEFLBL	markCursor,near
	push	bx
	mov	bx,ss:[PSP_HEAP]
	test	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,40h
	jz	mcu1			; the screen hasn't been used yet
mcu9:	pop	bx
	ret
	DEFLBL	screenCursor,near
	push	bx
	mov	bx,ss:[PSP_HEAP]
mcu1:	cmp	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,0
	je	mcu9			; no BAS program is running
	or	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,40h
	pop	bx
	DEFLBL	hideCursor,near
	push	dx
	mov	dl,0			; DL = 0 to hide the cursor
hcu1:	push	bx
	mov	bx,ss:[PSP_HEAP]
	test	byte ptr ss:[bx].GFX_DATA.GFX_SAVED,40h
	jz	hcu9			; no BAS program is using the screen
	push	ax
	push	cx
	mov	dh,0			; (nothing to erase)
	mov	cx,-1			; keep the cursor's position
	mov	al,IOCTL_SETPOS
	call	ioctlCon
	pop	cx
	pop	ax
hcu9:	pop	bx
	pop	dx
	ret
ENDPROC	showCursor

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; ioctlCon
;
; Inputs:
;	AL = IOCTL code (eg, IOCTL_GETPOS)
;	CX, DX = IOCTL inputs, if any
;
; Outputs:
;	Same as DOS_HDL_IOCTL (eg, DX = result) for STDOUT
;
; Modifies:
;	AX, BX, DX
;
DEFPROC	ioctlCon
	mov	ah,DOS_HDL_IOCTL
	mov	bx,STDOUT
	int	21h
	ret
ENDPROC	ioctlCon

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; printArgs
;
; Used by "PRINT [args]"
;
; Since expressions are evaluated left-to-right, their results are pushed
; left-to-right as well.  And since the number of parameters is variable, we
; walk the stacked parameters back to the beginning, pushing the offset of
; each as we go, and then popping and printing our way back to the end again.
;
; Inputs:
;	N pairs of variable types/values pushed on stack
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX, DI, ES
;
DEFPROC	printArgs,FAR
	push	bp			; preserve BP (see genEnd)
	mov	bp,sp
	add	bp,6
	sub	bx,bx
	push	bx			; push end-of-args marker
	mov	bx,bp

pa1:	mov	al,[bp]			; AL = arg type
	test	al,al
	jz	pa3
pa2:	push	bp
	lea	bp,[bp+2]
	cmp	al,VAR_LONG		; if AL < VAR_LONG that's trouble
	jb	pa1
;
; Every value is 4 bytes: a VAR_LONG, or a far pointer to a VAR_STR or
; VAR_DOUBLE (since doubles, like strings, are always passed by reference).
; If AL > VAR_DOUBLE that's trouble, because we don't know how to print
; VAR_FUNC or VAR_ARRAY variables.
;
	ASSERT	BE,<cmp al,VAR_DOUBLE>
	lea	bp,[bp+4]
	jmp	pa1

pa3:	lea	bp,[bp+2]
	sub	bp,bx
	mov	bx,bp			; BX = # bytes to clean off stack
;
; After printing any value, AL must be non-zero, so that we end on a new line
; (unless a separator follows the value).
;
pa4v:	mov	al,VAR_NEWLINE

pa4:	pop	bp
	test	bp,bp			; end-of-args marker?
	jz	pa8			; yes

	mov	al,[bp]			; AL = arg type
	cmp	al,VAR_SEMI
	je	pa4a
	cmp	al,VAR_COMMA
	jne	pa5
	PRINTF	<CHR_TAB>
pa4a:	mov	al,VAR_NONE		; if we end on this, there's no NEWLINE
	jmp	pa4
;
; Check for numeric types first: VAR_LONG, and then VAR_DOUBLE (whose far
; pointer we simply pass along to the %f formatter).
;
pa5:	cmp	al,VAR_LONG
	jne	pa6
	mov	ax,[bp+2]
	mov	dx,[bp+4]
;
; As the itoa code in sprintf.asm explains, we use the '#' (hash) flag with
; decimal output to signify that a space should precede positive values.
;
	PRINTF	<"%#ld ">,ax,dx		; DX:AX = 32-bit value
	jmp	pa4v
;
; VAR_DOUBLE is next, whose far pointer we simply pass to the %f formatter.
;
pa6:	cmp	al,VAR_DOUBLE
	jne	pa6a
	mov	ax,[bp+2]
	mov	dx,[bp+4]
	PRINTF	<"%#f ">,ax,dx		; DX:AX -> double
	jmp	pa4v
;
; Last but not least, VAR_STR, which we must release after printing, since
; it may be a temporary string (eg, the result of a string operation).
;
pa6a:	cmp	al,VAR_STR
	jne	pa4			; not a string type

	push	ds			; save DS
	lds	si,[bp+2]		; DS:SI = string pointer
	mov	cx,ds
	jcxz	pa7a			; nothing to do for null pointer
	call	writeStr		; write the string at DS:SI to STDOUT
	les	di,[bp+2]
	call	releaseStr

pa7a:	pop	ds			; restore DS
	jmp	pa4v
;
; We've reached the end of arguments, wrap it up.
;
pa8:	test	al,al			; unless AL is zero
	jz	pa9			; we want to end on a new line
	PRINTF	<13,10>

pa9:	pop	bp			; restore BP
	pop	dx			; remove return address
	pop	cx
	add	sp,bx			; clean the stack
	push	cx			; restore the return address
	push	dx
	ret
ENDPROC	printArgs

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; printEcho
;
; Inputs:
;	None
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX
;
DEFPROC	printEcho,FAR
	mov	bx,ss:[PSP_HEAP]
	test	ss:[bx].CMD_FLAGS,CMD_NOECHO
	mov	bx,offset STR_ON
	jz	pe1
	mov	bx,offset STR_OFF
pe1:	PRINTF	<"ECHO is %ls",13,10>,bx,cs
	ret
ENDPROC	printEcho

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; printLine
;
; Inputs:
;	Pointer to length-prefixed string pushed on stack
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX, SI
;
DEFPROC	printLine,FAR
	mov	bx,ss:[PSP_HEAP]
	test	ss:[bx].CMD_FLAGS,CMD_NOECHO
	jz	pl1
	ret	4
pl1:	call	endLine			; start a new line, if needed
	PRINTF	<"@">			; and fall into printStr
ENDPROC	printLine

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; printStr
;
; Inputs:
;	Pointer to length-prefixed string pushed on stack
;
; Outputs:
;	None
;
; Modifies:
;	AX, BX, CX, DX, SI
;
DEFPROC	printStr,FAR
	ARGVAR	pStr,dword
	ENTER
	push	ds
	lds	si,[pStr]		; DS:SI -> length-prefixed string
	call	writeStrCRLF
	pop	ds
	LEAVE
	RETURN
ENDPROC	printStr

;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;
; writeStr
;
; Inputs:
;	DS:SI -> length-prefixed string
;
; Outputs:
;	AX = # bytes printed
;	SI updated to end of string
;
; Modifies:
;	AX, CX, DX, SI
;
DEFPROC	writeStr
	push	bx
	lodsb				; AL = string length (255 max)
	mov	ah,0
	xchg	cx,ax			; CX = length
	mov	dx,si			; DS:DX -> data
	add	si,cx
	mov	bx,STDOUT
	mov	ah,DOS_HDL_WRITE
	int	21h
	pop	bx
	ret
ENDPROC	writeStr

